// Builds js/reference.js from the reference recording (the original voice).
//
//   node tools/make-reference.mjs assets/voices/male1.mp3
//
// Needs ffmpeg on the PATH to decode the mp3. For every consonant it stores where the cut goes
// (ms from the start of its sprite slot), as found by the automatic detector plus the hand-set
// CUT_MS overrides, and for the calibration sounds where the vowel starts. Other voices are
// aligned to this table at load time (see VoiceBank in js/engine.js).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const mp3 = process.argv[2];
if (!mp3) { console.error('usage: node tools/make-reference.mjs <reference.mp3>'); process.exit(1); }
const sr = 44100;
const raw = execFileSync('ffmpeg', ['-v', 'error', '-i', mp3, '-f', 'f32le', '-ac', '1', '-ar', String(sr), '-'], { maxBuffer: 1 << 29 });
const samples = new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4);

const here = f => pathToFileURL(resolve(new URL('..', import.meta.url).pathname, f)).href;
const { VoiceBank } = await import(here('js/engine.js'));
const { PHONEMES, CALIBRATION_IDS } = await import(here('js/phonemes.js'));
const { SPRITES } = await import(here('js/sprites.js'));
const { formantOnsetMs } = await import(here('js/dsp.js'));

const bank = new VoiceBank({ samples, sampleRate: sr, calibrate: false });
const r1 = v => Math.round(v * 10) / 10;
const cuts = {}, cal = {};
for (const p of PHONEMES) {
  if (p.kind !== 'consonant') continue;
  const [slot] = SPRITES[`${p.id}_1`];
  const c = bank.clips.get(`${p.id}_1`);
  const from = (c._a / sr) * 1000 - slot;
  cuts[p.id] = [r1(from), r1(from + (bank.units.get(p.id).x.length / sr) * 1000)];
}
for (const id of CALIBRATION_IDS) {
  const [start, dur] = SPRITES[`${id}_1`];
  const a = Math.round((start / 1000) * sr), b = Math.min(samples.length, Math.round(((start + dur + 40) / 1000) * sr));
  cal[id] = r1(formantOnsetMs(samples.subarray(a, b), sr));
}
const fmt = o => '{ ' + Object.entries(o).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(', ') + ' }';
writeFileSync(new URL('../js/reference.js', import.meta.url), `// Generated by tools/make-reference.mjs from ${mp3.split('/').pop()}. Do not edit by hand.
// CUT_REF: consonant id -> [start, end] of the part to keep, in ms from the start of its sprite slot.
export const CUT_REF = ${fmt(cuts)};
// CAL_REF: calibration sound id -> where its vowel starts, in ms from the start of its slot.
export const CAL_REF = ${fmt(cal)};
`);
console.log('wrote js/reference.js');
